import { useLocalSearchParams } from "expo-router";
import { FileDown, Printer } from "lucide-react-native";
import { useState } from "react";
import { Image, View } from "react-native";
import { MODES } from "@/components/FeeStatement";
import { useToast } from "@/components/toast";
import { Alert, Button, Divider, Enter, ErrorState, Loading, PageHeader, Row, Screen, Stack, Txt } from "@/components/ui";
import { esc, printHtml, printPage, sharePdf } from "@/lib/files";
import { formatDate, money } from "@/lib/format";
import { absolute } from "@/lib/server";
import { useTheme } from "@/lib/theme";
import type { Payment } from "@/lib/types";
import { useApi } from "@/lib/useApi";

type Receipt = {
  school: { name: string; address: string; currency: string; logo: string | null };
  section_name: string | null;
  academic_year: string;
  payment: Payment;
};

const modeLabel = (p: Payment) => `${MODES.find((m) => m.key === p.mode)?.label ?? p.mode}${p.reference ? ` · ${p.reference}` : ""}`;

function receiptHtml(r: Receipt) {
  const { school, payment: p } = r;
  const cur = school.currency;
  const lines = p.allocations.map((a) => `<tr><td>${esc(a.name)}</td><td class="right">${esc(money(a.amount, cur))}</td></tr>`).join("");
  return printPage(`Receipt ${p.receipt_no}`, `
    <div style="max-width:560px;margin:0 auto">
    <div class="head"><div>${school.logo ? `<img src="${esc(absolute(school.logo))}" style="height:52px;float:left;margin-right:12px">` : ""}<h1>${esc(school.name)}</h1>${school.address ? `<div class="soft">${esc(school.address)}</div>` : ""}</div></div>
    <div style="display:flex;justify-content:space-between;align-items:baseline"><h2 style="margin:0">${p.is_reversal ? "Reversal" : "Fee receipt"}</h2><span style="font-family:monospace">${esc(p.receipt_no)}</span></div>
    ${p.is_reversed ? `<p class="bold" style="color:#b91c1c">This payment was later reversed.</p>` : ""}
    <table style="margin-top:12px"><tbody>
      <tr><td class="soft">Student</td><td>${esc(p.student_name)} (Adm. ${esc(p.admission_no)})</td></tr>
      <tr><td class="soft">Class</td><td>${esc(r.section_name ?? "-")} · ${esc(r.academic_year)}</td></tr>
      <tr><td class="soft">Date</td><td>${esc(formatDate(p.paid_on))}</td></tr>
      <tr><td class="soft">Mode</td><td>${esc(modeLabel(p))}</td></tr>
      ${p.notes ? `<tr><td class="soft">Note</td><td>${esc(p.notes)}</td></tr>` : ""}
    </tbody></table>
    <table><thead><tr><th>For</th><th class="right">Amount</th></tr></thead><tbody>${lines}</tbody>
    <tfoot><tr class="bold"><td>Total</td><td class="right">${esc(money(p.amount, cur))}</td></tr></tfoot></table>
    <p class="soft" style="font-size:11px;margin-top:24px">Received by ${esc(p.received_by_name)}. This receipt was generated by the school's system.</p>
    </div>`);
}

export default function ReceiptPage() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const { c, lift } = useTheme();
  const receipt = useApi<Receipt>(`payments/${id}/receipt/`);
  const toast = useToast();
  const [busy, setBusy] = useState<"print" | "pdf" | null>(null);
  if (receipt.error && !receipt.data) return <Screen><ErrorState message={receipt.error} onRetry={receipt.reload} /></Screen>;
  if (!receipt.data) return <Screen><Loading variant="text" /></Screen>;
  const r = receipt.data;
  const { school, payment: p } = r;
  const cur = school.currency;
  const doIt = async (kind: "print" | "pdf") => {
    setBusy(kind);
    try {
      if (kind === "print") await printHtml(receiptHtml(r));
      else await sharePdf(receiptHtml(r), `Receipt ${p.receipt_no}`);
    } catch (e) {
      toast.error(e, "Could not prepare the receipt.");
    } finally {
      setBusy(null);
    }
  };
  const facts: [string, string][] = [
    ["Student", `${p.student_name} (Adm. ${p.admission_no})`],
    ["Class", `${r.section_name ?? "-"} · ${r.academic_year}`],
    ["Date", formatDate(p.paid_on)],
    ["Mode", modeLabel(p)],
    ...(p.notes ? [["Note", p.notes] as [string, string]] : []),
  ];
  return (
    <Screen>
      <PageHeader back="Back" title={p.is_reversal ? "Reversal" : "Fee receipt"} subtitle={p.receipt_no}
        actions={<><Button icon={Printer} busy={busy === "print"} onPress={() => doIt("print")}>Print</Button><Button variant="secondary" icon={FileDown} busy={busy === "pdf"} onPress={() => doIt("pdf")}>Save PDF</Button></>} />
      <Enter>
        <View style={[{ maxWidth: 560, width: "100%", alignSelf: "center", borderRadius: 18, borderWidth: 1, borderColor: c.line, backgroundColor: c.surface, padding: 20 }, lift]}>
          <Row gap={14} style={{ paddingBottom: 14 }}>
            {school.logo && <Image source={{ uri: absolute(school.logo) }} style={{ width: 52, height: 52 }} resizeMode="contain" />}
            <View style={{ flex: 1 }}>
              <Txt size="lg" weight="semibold">{school.name}</Txt>
              {school.address ? <Txt size="sm" soft>{school.address}</Txt> : null}
            </View>
          </Row>
          <Divider />
          <Row justify="space-between" style={{ paddingVertical: 14 }}>
            <Txt weight="semibold">{p.is_reversal ? "Reversal" : "Fee receipt"}</Txt>
            <Txt size="sm" style={{ fontFamily: "monospace" }}>{p.receipt_no}</Txt>
          </Row>
          {p.is_reversed && <Alert style={{ marginBottom: 12 }}>This payment was later reversed.</Alert>}
          <Stack gap={8}>
            {facts.map(([k, v]) => (
              <Row key={k} align="flex-start" gap={12}>
                <Txt size="sm" soft style={{ width: 80 }}>{k}</Txt>
                <Txt size="sm" style={{ flex: 1 }}>{v}</Txt>
              </Row>
            ))}
          </Stack>
          <View style={{ marginTop: 16, borderTopWidth: 1, borderColor: c.line }}>
            <Row justify="space-between" style={{ paddingVertical: 8, borderBottomWidth: 1, borderColor: c.line }}>
              <Txt size="xs" soft upper>For</Txt><Txt size="xs" soft upper>Amount</Txt>
            </Row>
            {p.allocations.map((a) => (
              <Row key={a.due} justify="space-between" style={{ paddingVertical: 9, borderBottomWidth: 1, borderColor: c.line }}>
                <Txt size="sm" style={{ flex: 1 }}>{a.name}</Txt><Txt size="sm" tabular>{money(a.amount, cur)}</Txt>
              </Row>
            ))}
            <Row justify="space-between" style={{ paddingVertical: 10 }}>
              <Txt weight="semibold">Total</Txt><Txt weight="semibold" tabular>{money(p.amount, cur)}</Txt>
            </Row>
          </View>
          <Txt size="xs" soft style={{ marginTop: 18 }}>Received by {p.received_by_name}. This receipt was generated by the school&apos;s system.</Txt>
        </View>
      </Enter>
    </Screen>
  );
}
