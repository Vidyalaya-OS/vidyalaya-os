"use client";

import { useParams } from "next/navigation";
import { MODES } from "@/components/FeeStatement";
import { Printer } from "lucide-react";
import { Alert, Button, ErrorState, Loading } from "@/components/ui";
import { formatDate, money } from "@/lib/format";
import { Payment } from "@/lib/types";
import { useApi } from "@/lib/useApi";

type Receipt = {
  school: { name: string; address: string; currency: string; logo: string | null };
  section_name: string | null;
  academic_year: string;
  payment: Payment;
};

export default function ReceiptPage() {
  const { id } = useParams<{ id: string }>();
  const receipt = useApi<Receipt>(`payments/${id}/receipt/`);
  if (receipt.error && !receipt.data) return <ErrorState message={receipt.error} onRetry={receipt.reload} />;
  if (!receipt.data) return <Loading variant="text" />;
  const { school, payment: p } = receipt.data;
  const cur = school.currency;
  return (
    <>
      <div className="mb-4 flex items-center justify-between gap-2 print:hidden">
        <button onClick={() => window.history.back()} className="text-sm font-medium text-soft hover:text-brand">← Back</button>
        <Button onClick={() => window.print()}><Printer aria-hidden /> Print or save as PDF</Button>
      </div>
      <article className="mx-auto max-w-xl animate-pop rounded-2xl border border-line bg-surface p-5 text-sm shadow-[var(--shadow-lift)] sm:p-8 print:animate-none print:border-0 print:p-0 print:shadow-none print:text-black">
        <header className="flex items-center gap-4 border-b border-line pb-4">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          {school.logo && <img src={school.logo} alt="" className="h-14 w-14 object-contain" />}
          <div>
            <h1 className="text-lg font-semibold">{school.name}</h1>
            {school.address && <p className="text-soft">{school.address}</p>}
          </div>
        </header>
        <div className="flex items-baseline justify-between py-4">
          <h2 className="text-base font-semibold">{p.is_reversal ? "Reversal" : "Fee receipt"}</h2>
          <span className="font-mono">{p.receipt_no}</span>
        </div>
        {p.is_reversed && <div className="mb-3"><Alert>This payment was later reversed.</Alert></div>}
        <dl className="grid grid-cols-2 gap-y-2">
          <dt className="text-soft">Student</dt><dd>{p.student_name} (Adm. {p.admission_no})</dd>
          <dt className="text-soft">Class</dt><dd>{receipt.data.section_name ?? "-"} · {receipt.data.academic_year}</dd>
          <dt className="text-soft">Date</dt><dd>{formatDate(p.paid_on)}</dd>
          <dt className="text-soft">Mode</dt><dd>{MODES.find((m) => m.key === p.mode)?.label ?? p.mode}{p.reference ? ` · ${p.reference}` : ""}</dd>
          {p.notes && <><dt className="text-soft">Note</dt><dd>{p.notes}</dd></>}
        </dl>
        <table className="mt-4 w-full text-left">
          <thead><tr className="border-y border-line text-xs uppercase tracking-wide text-soft"><th className="py-2">For</th><th className="py-2 text-right">Amount</th></tr></thead>
          <tbody>
            {p.allocations.map((a) => (
              <tr key={a.due} className="border-b border-line"><td className="py-2">{a.name}</td><td className="py-2 text-right tabular-nums">{money(a.amount, cur)}</td></tr>
            ))}
          </tbody>
          <tfoot><tr className="font-semibold"><td className="py-2">Total</td><td className="py-2 text-right tabular-nums">{money(p.amount, cur)}</td></tr></tfoot>
        </table>
        <p className="mt-6 text-xs text-soft">Received by {p.received_by_name}. This receipt was generated by the school&apos;s system.</p>
      </article>
    </>
  );
}
